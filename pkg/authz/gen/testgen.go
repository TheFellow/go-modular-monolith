func renderModuleModelTests(tree *ast.Schema, moduleName, importPath string) ([]byte, error) {
	actionNS, actions, err := moduleActions(tree)
	if err != nil {
		return nil, fmt.Errorf("%s schema tests: %w", moduleName, err)
	}
	entityNS, entityName, entityDef, err := moduleEntity(tree, actionNS, actions)
	if err != nil {
		return nil, fmt.Errorf("%s schema tests: %w", moduleName, err)
	}

	goEntity := exportedName(string(entityName))
	attrs := sortedFields(entityDef.Shape)
	hasTags, err := entityHasStringTags(entityDef)
	if err != nil {
		return nil, fmt.Errorf("%s schema tests: entity %s: %w", moduleName, entityName, err)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by authz/gen from %s. DO NOT EDIT.\n\n", schemaFile)
	b.WriteString("package authz_test\n\n")
	fmt.Fprintf(&b, "import (\n\t\"testing\"\n\n\tmoduleauthz %q\n", importPath)
	b.WriteString("\t\"github.com/TheFellow/go-modular-monolith/pkg/testutil\"\n\tcedar \"github.com/cedar-policy/cedar-go\"\n\t\"github.com/cedar-policy/cedar-go/x/exp/schema\"\n\t\"github.com/cedar-policy/cedar-go/x/exp/schema/validate\"\n)\n\n")
	fmt.Fprintf(&b, "func Test%sCedarEntity(t *testing.T) {\n", goEntity)
	b.WriteString("\tt.Parallel()\n\n")
	fmt.Fprintf(&b, "\tmodel := moduleauthz.%s{\n", goEntity)
	b.WriteString("\t\tUID: cedar.NewEntityUID(\"Wrong::Type\", \"test-id\"),\n")
	if hasTags {
		b.WriteString("\t\tTags: map[string]string{\"audience\": \"members\", \"featured\": \"\"},\n")
	}
	for _, attr := range attrs {
		value, _, err := testValues(tree, entityNS, entityDef.Shape[attr].Type, string(attr))
		if err != nil {
			return nil, fmt.Errorf("%s schema tests: attribute %s: %w", moduleName, attr, err)
		}
		fmt.Fprintf(&b, "\t\t%s: %s,\n", exportedName(string(attr)), value)
	}
	b.WriteString("\t}\n\n")
	b.WriteString("\tgot := model.CedarEntity()\n")
	b.WriteString("\twant := cedar.Entity{\n")
	fmt.Fprintf(&b, "\t\tUID: cedar.NewEntityUID(moduleauthz.%sType, \"test-id\"),\n", goEntity)
	b.WriteString("\t\tParents: cedar.NewEntityUIDSet(),\n")
	b.WriteString("\t\tAttributes: cedar.NewRecord(cedar.RecordMap{\n")
	for _, attr := range attrs {
		_, value, err := testValues(tree, entityNS, entityDef.Shape[attr].Type, string(attr))
		if err != nil {
			return nil, err
		}
		fmt.Fprintf(&b, "\t\t\tmoduleauthz.%s%sAttr: %s,\n", goEntity, exportedName(string(attr)), value)
	}
	b.WriteString("\t\t}),\n")
	if hasTags {
		b.WriteString("\t\tTags: cedar.NewRecord(cedar.RecordMap{\n")
		b.WriteString("\t\t\t\"audience\": cedar.String(\"members\"),\n")
		b.WriteString("\t\t\t\"featured\": cedar.String(\"\"),\n")
		b.WriteString("\t\t}),\n")
	} else {
		b.WriteString("\t\tTags: cedar.NewRecord(nil),\n")
	}
	b.WriteString("\t}\n\n")
	b.WriteString("\ttestutil.Equals(t, got, want)\n")
	b.WriteString("\tvar parsed schema.Schema\n")
	b.WriteString("\ttestutil.Ok(t, parsed.UnmarshalCedar([]byte(moduleauthz.Schema)))\n")
	b.WriteString("\tresolved, err := parsed.Resolve()\n")
	b.WriteString("\ttestutil.Ok(t, err)\n")
	b.WriteString("\ttestutil.Ok(t, validate.New(resolved).Entity(got))\n")
	b.WriteString("}\n")

	return format.Source(b.Bytes())
}

func testValues(tree *ast.Schema, ns types.Path, typ ast.IsType, attr string) (model, cedarValue string, err error) {
	goType, _, err := cedarType(typ)
	if err != nil {
		return "", "", err
	}
	id := strings.ToLower(attr)
	switch goType {
	case "string":
		return fmt.Sprintf("%q", "test-"+id), fmt.Sprintf("cedar.String(%q)", "test-"+id), nil
	case "int64":
		return "42", "cedar.Long(42)", nil
	case "bool":
		return "true", "cedar.Boolean(true)", nil
	case "cedar.EntityUID":
		entityType, err := resolveTestEntityType(tree, ns, typ)
		if err != nil {
			return "", "", err
		}
		value := fmt.Sprintf("cedar.NewEntityUID(%q, %q)", entityType, "test-"+id)
		return value, value, nil
	default:
		return "", "", fmt.Errorf("unsupported Go type %s", goType)
	}
}

func resolveTestEntityType(tree *ast.Schema, ns types.Path, typ ast.IsType) (string, error) {
	var ref string
	switch typ := typ.(type) {
	case ast.EntityTypeRef:
		ref = string(typ)
	case ast.TypeRef:
		ref = string(typ)
	default:
		return "", fmt.Errorf("Cedar type %T is not an entity reference", typ)
	}

	for _, path := range entityRefCandidates(ns, ref) {
		if schemaDeclaresEntityType(tree, path) {
			return string(path), nil
		}
	}
	return "", fmt.Errorf("entity type %q is not declared", ref)
}

func entityRefCandidates(ns types.Path, ref string) []types.Path {
	if ns != "" && !strings.Contains(ref, "::") {
		return []types.Path{types.Path(string(ns) + "::" + ref), types.Path(ref)}
	}
	return []types.Path{types.Path(ref)}
}

func schemaDeclaresEntityType(tree *ast.Schema, path types.Path) bool {
	text := string(path)
	idx := strings.LastIndex(text, "::")
	if idx < 0 {
		name := types.Ident(text)
		_, entityOK := tree.Entities[name]
		_, enumOK := tree.Enums[name]
		return entityOK || enumOK
	}
	ns, name := types.Path(text[:idx]), types.Ident(text[idx+2:])
	declarations, ok := tree.Namespaces[ns]
	if !ok {
		return false
	}
	_, entityOK := declarations.Entities[name]
	_, enumOK := declarations.Enums[name]
	return entityOK || enumOK
}
