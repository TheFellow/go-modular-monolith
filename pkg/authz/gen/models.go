const schemaFile = "schema.cedarschema"

// generateModuleModels turns each module schema into its small Cedar boundary
// model. Domain models keep business behavior; generated models own only the
// authorization representation.
func generateModuleModels(modules []modulePolicy) {
	for _, module := range modules {
		path := filepath.Join(module.directory, schemaFile)
		src, err := os.ReadFile(path)
		must(err)

		var s schema.Schema
		s.SetFilename(path)
		must(s.UnmarshalCedar(src))
		resolved, err := s.Resolve()
		must(err)
		must(validatePolicies(resolved, filepath.Join(module.directory, "policies.cedar")))

		out, err := renderModuleModels(s.AST(), module.moduleName)
		must(err)
		must(os.WriteFile(filepath.Join(module.directory, "models_gen.go"), out, 0o644))

		tests, err := renderModuleModelTests(s.AST(), module.moduleName, module.importPath)
		must(err)
		must(os.WriteFile(filepath.Join(module.directory, "models_gen_test.go"), tests, 0o644))
	}
}

func renderModuleModels(tree *ast.Schema, moduleName string) ([]byte, error) {
	actionNS, actions, err := moduleActions(tree)
	if err != nil {
		return nil, fmt.Errorf("%s schema: %w", moduleName, err)
	}
	entityNS, entityName, entityDef, err := moduleEntity(tree, actionNS, actions)
	if err != nil {
		return nil, fmt.Errorf("%s schema: %w", moduleName, err)
	}
	if err := validateGeneratedNames(entityName, entityDef.Shape, actions); err != nil {
		return nil, fmt.Errorf("%s schema: %w", moduleName, err)
	}

	goEntity := exportedName(string(entityName))
	entityType := qualifyPath(entityNS, string(entityName))
	actionType := qualifyPath(actionNS, "Action")
	attrs := sortedFields(entityDef.Shape)
	hasTags, err := entityHasStringTags(tree, entityNS, entityDef)
	if err != nil {
		return nil, fmt.Errorf("entity %s: %w", entityType, err)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by authz/gen from %s. DO NOT EDIT.\n\n", schemaFile)
	b.WriteString("package authz\n\n")
	b.WriteString("import (\n\t_ \"embed\"\n\t\"sync\"\n\n\tcedar \"github.com/cedar-policy/cedar-go\"\n\t\"github.com/cedar-policy/cedar-go/x/exp/schema\"\n\t\"github.com/cedar-policy/cedar-go/x/exp/schema/resolved\"\n\t\"github.com/cedar-policy/cedar-go/x/exp/schema/validate\"\n)\n\n")
	fmt.Fprintf(&b, "//go:embed %s\nvar Schema string\n\n", schemaFile)
	fmt.Fprintf(&b, "const (\n\t%sType cedar.EntityType = %q\n\tResourceType cedar.EntityType = %sType\n\tActionType cedar.EntityType = %q\n", goEntity, entityType, goEntity, actionType)
	for _, attr := range attrs {
		fmt.Fprintf(&b, "\t%s%sAttr = %q\n", goEntity, exportedName(string(attr)), attr)
	}
	b.WriteString(")\n\n")
	b.WriteString("var (\n\tschemaOnce sync.Once\n\tresolvedSchema *resolved.Schema\n\tschemaErr error\n)\n\n")
	b.WriteString("// ValidateEntity validates entity against the module's Cedar schema.\n")
	b.WriteString("func ValidateEntity(entity cedar.Entity) error {\n")
	b.WriteString("\tschemaOnce.Do(func() {\n")
	b.WriteString("\t\tvar parsed schema.Schema\n")
	fmt.Fprintf(&b, "\t\tparsed.SetFilename(%q)\n", schemaFile)
	b.WriteString("\t\tif schemaErr = parsed.UnmarshalCedar([]byte(Schema)); schemaErr != nil {\n\t\t\treturn\n\t\t}\n")
	b.WriteString("\t\tresolvedSchema, schemaErr = parsed.Resolve()\n")
	b.WriteString("\t})\n")
	b.WriteString("\tif schemaErr != nil {\n\t\treturn schemaErr\n\t}\n")
	b.WriteString("\treturn validate.New(resolvedSchema).Entity(entity)\n")
	b.WriteString("}\n\n")

	b.WriteString("var (\n")
	actionNames := make([]string, 0, len(actions))
	for name := range actions {
		actionNames = append(actionNames, string(name))
	}
	slices.Sort(actionNames)
	for _, name := range actionNames {
		fmt.Fprintf(&b, "\tAction%s = cedar.NewEntityUID(ActionType, %q)\n", exportedName(name), name)
	}
	b.WriteString(")\n\n")

	fmt.Fprintf(&b, "// %s is the Cedar-facing authorization model for %s.\n", goEntity, entityType)
	fmt.Fprintf(&b, "type %s struct {\n\tUID cedar.EntityUID\n", goEntity)
	if hasTags {
		b.WriteString("\tTags map[string]string\n")
	}
	for _, attr := range attrs {
		field := entityDef.Shape[attr]
		if field.Optional {
			return nil, fmt.Errorf("entity %s attribute %s: optional attributes are not supported", entityType, attr)
		}
		goType, _, err := cedarType(tree, entityNS, field.Type)
		if err != nil {
			return nil, fmt.Errorf("entity %s attribute %s: %w", entityType, attr, err)
		}
		fmt.Fprintf(&b, "\t%s %s\n", exportedName(string(attr)), goType)
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "// CedarEntity converts m to the entity shape declared in %s.\n", schemaFile)
	fmt.Fprintf(&b, "func (m %s) CedarEntity() cedar.Entity {\n", goEntity)
	if hasTags {
		b.WriteString("\ttags := make(cedar.RecordMap, len(m.Tags))\n")
		b.WriteString("\tfor key, value := range m.Tags {\n\t\ttags[cedar.String(key)] = cedar.String(value)\n\t}\n\n")
	}
	fmt.Fprintf(&b, "\treturn cedar.Entity{\n\t\tUID: cedar.NewEntityUID(%sType, m.UID.ID),\n", goEntity)
	b.WriteString("\t\tParents: cedar.NewEntityUIDSet(),\n\t\tAttributes: cedar.NewRecord(cedar.RecordMap{\n")
	for _, attr := range attrs {
		typ := entityDef.Shape[attr].Type
		_, converter, err := cedarType(tree, entityNS, typ)
		if err != nil {
			return nil, err
		}
		name := exportedName(string(attr))
		if referencedType, ok, err := referencedEntityType(tree, entityNS, typ); err != nil {
			return nil, err
		} else if ok {
			fmt.Fprintf(&b, "\t\t\t%s%sAttr: cedar.NewEntityUID(%q, m.%s.ID),\n", goEntity, name, referencedType, name)
		} else {
			fmt.Fprintf(&b, "\t\t\t%s%sAttr: %s(m.%s),\n", goEntity, name, converter, name)
		}
	}
	b.WriteString("\t\t}),\n")
	if hasTags {
		b.WriteString("\t\tTags: cedar.NewRecord(tags),\n")
	} else {
		b.WriteString("\t\tTags: cedar.NewRecord(nil),\n")
	}
	b.WriteString("\t}\n}\n")

	return format.Source(b.Bytes())
}

func validateGeneratedNames(entityName types.Ident, shape ast.RecordType, actions ast.Actions) error {
	goEntity := exportedName(string(entityName))
	if !token.IsIdentifier(goEntity) {
		return fmt.Errorf("entity name %q does not normalize to a Go identifier", entityName)
	}
	if goEntity == "Action" {
		return fmt.Errorf("entity name %q conflicts with the generated Action type", entityName)
	}

	fields := map[string]types.String{}
	for _, attr := range sortedFields(shape) {
		name := exportedName(string(attr))
		if !token.IsIdentifier(name) {
			return fmt.Errorf("attribute %q does not normalize to a Go identifier", attr)
		}
		switch name {
		case "UID", "Tags", "CedarEntity":
			return fmt.Errorf("attribute %q conflicts with the generated %s member", attr, name)
		}
		if previous, ok := fields[name]; ok {
			return fmt.Errorf("attributes %q and %q both normalize to field name %q", previous, attr, name)
		}
		fields[name] = attr
	}

	actionVars := map[string]types.String{}
	actionNames := make([]string, 0, len(actions))
	for action := range actions {
		actionNames = append(actionNames, string(action))
	}
	slices.Sort(actionNames)
	for _, action := range actionNames {
		name := "Action" + exportedName(action)
		if !token.IsIdentifier(name) {
			return fmt.Errorf("action %q does not normalize to a Go identifier", action)
		}
		if name == "ActionType" {
			return fmt.Errorf("action %q conflicts with the generated ActionType constant", action)
		}
		if previous, ok := actionVars[name]; ok {
			return fmt.Errorf("actions %q and %q both normalize to variable name %q", previous, action, name)
		}
		actionVars[name] = types.String(action)
	}
	return nil
}

func entityHasStringTags(tree *ast.Schema, ns types.Path, entity ast.Entity) (bool, error) {
	if entity.Tags == nil {
		return false, nil
	}
	goType, _, err := cedarType(tree, ns, entity.Tags)
	if err != nil {
		return false, fmt.Errorf("tags: %w", err)
	}
	if goType != "string" {
		return false, fmt.Errorf("tags: unsupported Cedar value type %v; only String is supported", entity.Tags)
	}
	return true, nil
}

func moduleActions(tree *ast.Schema) (types.Path, ast.Actions, error) {
	var foundNS types.Path
	var found ast.Actions
	for ns, declarations := range tree.Namespaces {
		if len(declarations.Actions) == 0 {
			continue
		}
		if found != nil {
			return "", nil, fmt.Errorf("expected actions in one namespace")
		}
		foundNS, found = ns, declarations.Actions
	}
	if found == nil {
		return "", nil, fmt.Errorf("no actions declared")
	}
	actionNames := make([]string, 0, len(found))
	for name := range found {
		actionNames = append(actionNames, string(name))
	}
	slices.Sort(actionNames)
	for _, name := range actionNames {
		action := found[types.String(name)]
		if action.AppliesTo == nil {
			continue
		}
		context, ok := action.AppliesTo.Context.(ast.RecordType)
		if !ok || len(context) != 0 {
			return "", nil, fmt.Errorf("action %s: non-empty action contexts are not supported", name)
		}
	}
	return foundNS, found, nil
}

func moduleEntity(tree *ast.Schema, actionNS types.Path, actions ast.Actions) (types.Path, types.Ident, ast.Entity, error) {
	var resource ast.EntityTypeRef
	for _, action := range actions {
		if action.AppliesTo == nil || len(action.AppliesTo.Resources) != 1 {
			return "", "", ast.Entity{}, fmt.Errorf("each action must apply to exactly one resource type")
		}
		if resource == "" {
			resource = action.AppliesTo.Resources[0]
		} else if resource != action.AppliesTo.Resources[0] {
			return "", "", ast.Entity{}, fmt.Errorf("all actions must use the same resource type")
		}
	}

	path := string(resource)
	if !strings.Contains(path, "::") {
		path = string(actionNS) + "::" + path
	}
	idx := strings.LastIndex(path, "::")
	if idx < 0 {
		def, ok := tree.Entities[types.Ident(path)]
		if !ok {
			return "", "", ast.Entity{}, fmt.Errorf("resource entity %s is not declared", path)
		}
		if len(def.ParentTypes) != 0 {
			return "", "", ast.Entity{}, fmt.Errorf("resource entity %s: parent types are not supported", path)
		}
		return "", types.Ident(path), def, nil
	}
	ns, name := types.Path(path[:idx]), types.Ident(path[idx+2:])
	declarations, ok := tree.Namespaces[ns]
	if !ok {
		return "", "", ast.Entity{}, fmt.Errorf("resource namespace %s is not declared", ns)
	}
	def, ok := declarations.Entities[name]
	if !ok {
		return "", "", ast.Entity{}, fmt.Errorf("resource entity %s is not declared", path)
	}
	if len(def.ParentTypes) != 0 {
		return "", "", ast.Entity{}, fmt.Errorf("resource entity %s: parent types are not supported", path)
	}
	return ns, name, def, nil
}

func cedarType(tree *ast.Schema, ns types.Path, typ ast.IsType) (goType, converter string, err error) {
	return resolveCedarType(tree, ns, typ, set.Set[types.Path]{})
}

func resolveCedarType(tree *ast.Schema, ns types.Path, typ ast.IsType, resolving set.Set[types.Path]) (goType, converter string, err error) {
	switch typ := typ.(type) {
	case ast.StringType:
		return "string", "cedar.String", nil
	case ast.LongType:
		return "int64", "cedar.Long", nil
	case ast.BoolType:
		return "bool", "cedar.Boolean", nil
	case ast.EntityTypeRef:
		if _, err := resolveEntityType(tree, ns, string(typ)); err != nil {
			return "", "", err
		}
		return "cedar.EntityUID", "cedar.EntityUID", nil
	case ast.TypeRef:
		switch string(typ) {
		case "String", "__cedar::String":
			return "string", "cedar.String", nil
		case "Long", "__cedar::Long":
			return "int64", "cedar.Long", nil
		case "Bool", "__cedar::Bool":
			return "bool", "cedar.Boolean", nil
		}
		for _, path := range refCandidates(ns, string(typ)) {
			if common, commonNS, ok := schemaCommonType(tree, path); ok {
				if resolving.Contains(path) {
					return "", "", fmt.Errorf("common type cycle at %s", path)
				}
				resolving.Add(path)
				goType, converter, err := resolveCedarType(tree, commonNS, common.Type, resolving)
				resolving.Remove(path)
				return goType, converter, err
			}
			if schemaDeclaresEntityType(tree, path) {
				return "cedar.EntityUID", "cedar.EntityUID", nil
			}
		}
		return "", "", fmt.Errorf("undefined Cedar type %q", typ)
	default:
		return "", "", fmt.Errorf("unsupported Cedar type %T", typ)
	}
}

func resolveEntityType(tree *ast.Schema, ns types.Path, ref string) (types.Path, error) {
	for _, path := range refCandidates(ns, ref) {
		if schemaDeclaresEntityType(tree, path) {
			return path, nil
		}
	}
	return "", fmt.Errorf("entity type %q is not declared", ref)
}

func referencedEntityType(tree *ast.Schema, ns types.Path, typ ast.IsType) (types.Path, bool, error) {
	switch typ := typ.(type) {
	case ast.EntityTypeRef:
		path, err := resolveEntityType(tree, ns, string(typ))
		return path, err == nil, err
	case ast.TypeRef:
		for _, path := range refCandidates(ns, string(typ)) {
			if common, commonNS, ok := schemaCommonType(tree, path); ok {
				return referencedEntityType(tree, commonNS, common.Type)
			}
			if schemaDeclaresEntityType(tree, path) {
				return path, true, nil
			}
		}
	}
	return "", false, nil
}

func refCandidates(ns types.Path, ref string) []types.Path {
	if ns != "" && !strings.Contains(ref, "::") {
		return []types.Path{types.Path(string(ns) + "::" + ref), types.Path(ref)}
	}
	return []types.Path{types.Path(ref)}
}

func schemaCommonType(tree *ast.Schema, path types.Path) (ast.CommonType, types.Path, bool) {
	text := string(path)
	idx := strings.LastIndex(text, "::")
	if idx < 0 {
		common, ok := tree.CommonTypes[types.Ident(text)]
		return common, "", ok
	}
	ns, name := types.Path(text[:idx]), types.Ident(text[idx+2:])
	declarations, ok := tree.Namespaces[ns]
	if !ok {
		return ast.CommonType{}, "", false
	}
	common, ok := declarations.CommonTypes[name]
	return common, ns, ok
}

func schemaDeclaresEntityType(tree *ast.Schema, path types.Path) bool {
	text := string(path)
	idx := strings.LastIndex(text, "::")
	if idx < 0 {
		name := types.Ident(text)
		_, entityOK := tree.Entities[name]
		_, enumOK := tree.Enums[name]
		return entityOK || enumOK
	}
	ns, name := types.Path(text[:idx]), types.Ident(text[idx+2:])
	declarations, ok := tree.Namespaces[ns]
	if !ok {
		return false
	}
	_, entityOK := declarations.Entities[name]
	_, enumOK := declarations.Enums[name]
	return entityOK || enumOK
}

func sortedFields(record ast.RecordType) []types.String {
	fields := make([]types.String, 0, len(record))
	for name := range record {
		fields = append(fields, name)
	}
	slices.Sort(fields)
	return fields
}

func qualifyPath(ns types.Path, name string) string {
	if ns == "" {
		return name
	}
	return string(ns) + "::" + name
}

func exportedName(name string) string {
	var out strings.Builder
	upper := true
	for _, r := range name {
		if r == '_' || r == '-' || r == ' ' {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		out.WriteRune(r)
	}
	return out.String()
}
